import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const origin = 'https://secondvoice-green.vercel.app';
const page = await fetch(origin);
assert.equal(page.status, 200);
const accepted = await fetch(`${origin}/api/tts/token`, { method: 'POST', headers: { Origin: origin } });
const data = await accepted.json();
assert.equal(accepted.status, 200, `Public request returned ${accepted.status}`);
assert.ok(data.token);
const crossOrigin = await fetch(`${origin}/api/tts/token`, { method: 'POST', headers: { Origin: 'https://example.com' } });
assert.equal(crossOrigin.status, 403);
const wav = await fetch(`${origin}/demo/original.wav`);
assert.equal(wav.status, 200);
const bytes = Buffer.from(await wav.arrayBuffer());
assert.equal(bytes.toString('ascii', 0, 4), 'RIFF');
const result = { origin, page: page.status, publicToken: accepted.status, crossOrigin: crossOrigin.status, recordingBytes: bytes.length, passed: true };
await mkdir('artifacts/live-verification', { recursive: true });
await writeFile('artifacts/live-verification/deployment.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
